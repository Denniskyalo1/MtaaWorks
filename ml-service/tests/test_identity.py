"""Tests for matching the name and phone number printed on a statement with the borrower's account.
The PDFs are generated by tools/make_synthetic_statement.py. Run from ml-service:   python -m pytest tests -v"""
import json
import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
pytest.importorskip("reportlab")
pytest.importorskip("pymupdf")

from fastapi.testclient import TestClient

import src.api as api
from src import pdf_rows
from src.identity import identities_agree, names_match, parse_identity, phones_match
from tools.make_synthetic_statement import build, build_pair

client = TestClient(api.app)
NAME, PHONE = "JOHN KAMAU DOE", "254712345678"


@pytest.fixture(scope="module")
def pdfs(tmp_path_factory):
    folder = tmp_path_factory.mktemp("identity")
    out = {}
    for layout in ("inline", "stacked", "block"):
        build(str(folder / f"{layout}.pdf"), "pw", "2026-01-01", 5, per_day=4, seed=41, customer=NAME, mobile=PHONE, layout=layout)
        out[layout] = (folder / f"{layout}.pdf").read_bytes()
    build(str(folder / "noheader.pdf"), "pw", "2026-01-01", 5, per_day=4, seed=42)
    out["noheader"] = (folder / "noheader.pdf").read_bytes()
    build(str(folder / "other.pdf"), "pw", "2026-03-01", 5, per_day=4, seed=43, customer="MARY WANJIKU OTIENO", mobile="254799000111")
    out["other"] = (folder / "other.pdf").read_bytes()
    build_pair(str(folder / "p1.pdf"), "pw", str(folder / "p2.pdf"), "pw", "2026-01-01", 8, per_day=4, seed=44, customer=NAME, mobile=PHONE)
    out["p1"], out["p2"] = (folder / "p1.pdf").read_bytes(), (folder / "p2.pdf").read_bytes()
    return out


def one(pdf, **form):
    return client.post("/score-statement", files={"file": ("s.pdf", pdf, "application/pdf")}, data={"password": "pw", **form})


@pytest.mark.parametrize("layout", ["inline", "stacked", "block"])
def test_name_and_number_are_read_in_each_header_layout(pdfs, layout):  # TC-S44
    assert pdf_rows.read_identity(pdfs[layout], "pw") == {"name": NAME, "phone": PHONE}


def test_header_text_forms():  # TC-S45
    assert parse_identity("Customer Name: JANE W DOE Mobile Number: +254 712 345 678 Date of Statement: 5 Oct") == {"name": "JANE W DOE", "phone": "254712345678"}
    assert parse_identity("No identity here") == {"name": None, "phone": None}


def test_names_match_whatever_the_order_or_middle_name():  # TC-S46
    assert names_match("JOHN KAMAU DOE", "Doe John") is True
    assert names_match("JOHN KAMAU DOE", "john doe") is True
    assert names_match("JOHN KAMAU DOE", "Mary Doe") is False
    assert names_match("", "John Doe") is None


def test_phone_formats_and_hidden_digits():  # TC-S47
    assert phones_match("254712345678", "0712345678") is True
    assert phones_match("2547****5678", "+254712345678") is True
    assert phones_match("254712345678", "0722345678") is False
    assert phones_match(None, "0712345678") is None


def test_a_statement_of_the_account_holder_passes(pdfs):  # TC-S48
    r = one(pdfs["inline"], expected_name="John Kamau Doe", expected_phone="0712345678")
    v = r.json()["validation"]
    assert r.status_code == 200 and v["identity_checked"] is True and v["name_matched"] is True and v["phone_matched"] is True


def test_another_persons_name_is_refused_without_repeating_it(pdfs):  # TC-S49
    r = one(pdfs["inline"], expected_name="Mary Wanjiku Otieno")
    assert r.status_code == 422 and "customer name" in r.json()["detail"]
    assert "JOHN" not in r.json()["detail"] and "MARY" not in r.json()["detail"].upper().replace("MARYS", "")


def test_a_different_phone_number_is_refused(pdfs):  # TC-S50
    r = one(pdfs["inline"], expected_name="John Doe", expected_phone="0722000111")
    assert r.status_code == 422 and "mobile number" in r.json()["detail"]


def test_without_expected_values_nothing_is_checked(pdfs):  # TC-S51
    v = one(pdfs["inline"]).json()["validation"]
    assert v["identity_checked"] is False and v["name_matched"] is None


def test_a_statement_with_no_readable_header_is_accepted_but_marked_unchecked(pdfs):  # TC-S52
    r = one(pdfs["noheader"], expected_name="Anyone Atall", expected_phone="0700000000")
    assert r.status_code == 200 and r.json()["validation"]["identity_checked"] is False


def test_the_check_can_be_switched_off(pdfs, monkeypatch):  # TC-S53
    monkeypatch.setenv("STATEMENT_IDENTITY_CHECK", "off")
    assert one(pdfs["inline"], expected_name="Mary Wanjiku Otieno").status_code == 200


def post_many(pdfs, names, **form):
    return client.post("/score-statements", files=[("files", (f"{n}.pdf", pdfs[n], "application/pdf")) for n in names],
                       data={"passwords": json.dumps(["pw"] * len(names)), **form})


def test_two_statements_with_the_same_customer_are_scored_together(pdfs):  # TC-S54
    r = post_many(pdfs, ["p1", "p2"], expected_name="John Doe", expected_phone="0712345678")
    assert r.status_code == 200 and r.json()["validation"]["identity_checked"] is True


def test_statements_showing_different_customers_are_refused(pdfs):  # TC-S55
    r = post_many(pdfs, ["inline", "other"])
    assert r.status_code == 422 and "different customer names or mobile numbers" in r.json()["detail"]
    assert identities_agree({"name": NAME, "phone": PHONE}, {"name": "MARY WANJIKU OTIENO", "phone": "254799000111"}) is False
