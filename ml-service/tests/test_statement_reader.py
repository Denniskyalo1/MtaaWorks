"""Tests for the statement readers and for scoring several statements together.
The PDFs are generated by tools/make_synthetic_statement.py, so no real statement is needed.
Run from the ml-service folder:   python -m pytest tests -v"""
import io
import json
import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
pytest.importorskip("reportlab")
pytest.importorskip("pymupdf")

from fastapi.testclient import TestClient
from pdfminer.pdfdocument import PDFPasswordIncorrect

import src.api as api
from src import pdf_rows, statement_parser as sp
from tools.make_synthetic_statement import build, build_pair

client = TestClient(api.app)


@pytest.fixture(scope="module")
def pdfs(tmp_path_factory):
    folder = tmp_path_factory.mktemp("pdfs")
    spec = {"a": ("2026-01-01", 5, 11), "b": ("2026-05-10", 4, 12), "gap": ("2026-09-20", 3, 13)}
    out = {}
    for name, (start, months, seed) in spec.items():
        path = folder / f"{name}.pdf"
        build(str(path), f"pw-{name}", start, months, per_day=6, seed=seed)
        out[name] = path.read_bytes()
    # two statements of one account (earlier and later period, overlapping by two weeks)
    build_pair(str(folder / "p1.pdf"), "pw-p1", str(folder / "p2.pdf"), "pw-p2", "2026-01-01", 8, overlap_days=14, seed=31)
    out["p1"], out["p2"] = (folder / "p1.pdf").read_bytes(), (folder / "p2.pdf").read_bytes()
    return out


def post_many(pdfs, names, passwords):
    return client.post("/score-statements",
                       files=[("files", (f"{n}.pdf", pdfs[n], "application/pdf")) for n in names],
                       data={"passwords": json.dumps(passwords)})


def test_fast_and_reliable_readers_give_identical_rows(pdfs):  # TC-S22
    fast, fast_summary = sp.read_statement(io.BytesIO(pdfs["a"]), "pw-a", method="fast")
    slow, slow_summary = sp.read_statement(io.BytesIO(pdfs["a"]), "pw-a", method="reliable")
    assert len(fast) > 300 and fast.equals(slow) and fast_summary == slow_summary


@pytest.mark.parametrize("valign", ["TOP", "MIDDLE", "BOTTOM"])
def test_wrapped_cells_give_identical_rows_whatever_the_vertical_alignment(valign, tmp_path):  # TC-S23
    path = tmp_path / "wrapped.pdf"
    build(str(path), "pw", "2026-01-01", 1, per_day=5, seed=21, wrap=True, valign=valign)
    data = path.read_bytes()
    fast, fast_summary = pdf_rows.read_fast(data, "pw")
    slow, slow_summary = pdf_rows.read_reliable(data, "pw", workers=1)
    assert len(fast) > 100 and fast == slow and fast_summary == slow_summary


def test_fast_reader_declines_when_rows_are_not_separated_by_rules(tmp_path):  # TC-S24
    path = tmp_path / "no_rules.pdf"
    build(str(path), "pw", "2026-01-01", 1, per_day=5, seed=22, rules=False)
    with pytest.raises(pdf_rows.FastReaderUnavailable):
        pdf_rows.read_fast(path.read_bytes(), "pw")


def test_automatic_mode_uses_fast_reader_when_totals_agree(pdfs):  # TC-S25
    df, summary = sp.read_statement(io.BytesIO(pdfs["a"]), "pw-a")
    assert sp.last_read_method() == "fast" and validate_totals(df, summary)


def validate_totals(df, summary):
    return abs(df["paid_in"].sum() - summary["paid_in"]) < 0.01 and abs(df["withdrawn"].sum() - summary["paid_out"]) < 0.01


def test_falls_back_to_reliable_reader_when_fast_totals_disagree(pdfs, monkeypatch):  # TC-S26
    real = pdf_rows.read_fast

    def wrong_totals(data, password):
        rows, summary = real(data, password)
        return rows[1:], summary          # one row missing, so the totals no longer agree

    monkeypatch.setattr(pdf_rows, "read_fast", wrong_totals)
    df, summary = sp.read_statement(io.BytesIO(pdfs["a"]), "pw-a")
    assert sp.last_read_method() == "reliable" and validate_totals(df, summary)


def test_any_error_in_the_fast_reader_falls_back_to_the_reliable_reader(pdfs, monkeypatch):  # TC-S27
    def broken(data, password):
        raise ValueError("unexpected text in the statement")

    monkeypatch.setattr(pdf_rows, "read_fast", broken)
    df, summary = sp.read_statement(io.BytesIO(pdfs["a"]), "pw-a")
    assert sp.last_read_method() == "reliable" and validate_totals(df, summary)


def test_other_lines_containing_total_do_not_break_the_fast_reader(pdfs):  # TC-S28
    rows, summary = pdf_rows.read_fast(pdfs["a"], "pw-a")   # the page has a "TOTAL (KES)" sentence before the summary
    assert len(rows) > 300 and summary is not None and summary["paid_in"] > 0


def test_falls_back_when_pymupdf_is_unavailable(pdfs, monkeypatch):  # TC-S29
    def unavailable(data, password):
        raise pdf_rows.FastReaderUnavailable("missing")

    monkeypatch.setattr(pdf_rows, "read_fast", unavailable)
    df, summary = sp.read_statement(io.BytesIO(pdfs["a"]), "pw-a")
    assert sp.last_read_method() == "reliable" and len(df) > 300


@pytest.mark.parametrize("method", ["fast", "reliable"])
def test_wrong_password_is_reported_by_both_readers(pdfs, method):  # TC-S30
    with pytest.raises(PDFPasswordIncorrect):
        sp.read_statement(io.BytesIO(pdfs["a"]), "wrong", method=method)


def test_two_statements_of_one_account_are_scored_together(pdfs):  # TC-S31
    r = post_many(pdfs, ["p1", "p2"], ["pw-p1", "pw-p2"])
    assert r.status_code == 200
    body = r.json()
    assert body["validation"]["files_read"] == 2 and body["months_in_statement"] >= 7
    assert body["validation"]["duplicate_rows_removed"] > 0       # the two-week overlap was counted once
    assert body["validation"]["parser"] == "fast" and body["result"]["tier"] in ("Tier 1", "Tier 2", "Tier 3")


def test_statements_of_different_accounts_are_refused(pdfs):  # TC-S32
    r = post_many(pdfs, ["a", "b"], ["pw-a", "pw-b"])         # two independent accounts with overlapping dates
    assert r.status_code == 422 and "same M-Pesa account" in r.json()["detail"]


def test_uploading_the_same_statement_twice_does_not_double_count(pdfs):  # TC-S33
    once = post_many(pdfs, ["a"], ["pw-a"]).json()
    twice = post_many(pdfs, ["a", "a"], ["pw-a", "pw-a"]).json()
    assert twice["validation"]["duplicate_rows_removed"] == once["validation"]["rows_read"]
    assert twice["validation"]["rows_read"] == once["validation"]["rows_read"]
    assert twice["features"] == once["features"]


def test_statements_with_a_gap_between_them_are_refused(pdfs):  # TC-S34
    r = post_many(pdfs, ["a", "gap"], ["pw-a", "pw-gap"])
    assert r.status_code == 422 and "continuous period" in r.json()["detail"]


def test_wrong_password_names_the_statement(pdfs):  # TC-S35
    r = post_many(pdfs, ["a", "b"], ["pw-a", "nope"])
    assert r.status_code == 400 and r.json()["detail"].startswith("Statement 2:")


def test_password_count_must_match_file_count(pdfs):  # TC-S36
    assert post_many(pdfs, ["a", "b"], ["pw-a"]).status_code == 422


def test_more_than_six_statements_are_refused(pdfs):  # TC-S37
    assert post_many(pdfs, ["a"] * 7, ["pw-a"] * 7).status_code == 422


def test_response_reports_the_parser_and_time(pdfs):  # TC-S38
    r = client.post("/score-statement", files={"file": ("a.pdf", pdfs["a"], "application/pdf")}, data={"password": "pw-a"})
    v = r.json()["validation"]
    assert r.status_code == 200 and v["parser"] == "fast" and 0 <= v["parse_seconds"] < 30
